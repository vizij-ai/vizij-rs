#!/usr/bin/env node
// Produce the package's `artifact/`: the module directory of Arora's
// animation module (`arora-animation-module`), as a device loads the guest
// from it —
//
//   artifact/<guest>.wasm — the guest, built with
//     `cargo build -p arora-animation-module --target wasm32-wasip1 --release`,
//     under the file name the crate's `module_dir::GUEST_FILE` gives it
//   artifact/header.json — the module's Arora header, from its Rust
//     declaration
//   artifact/records/ — the module's Arora records (its module record and the
//     records of the structures its functions take and return, in the `arora`
//     scope), in the layout a device's module directory carries
//
// `vizij-animation-artifact` writes the directory
// (`arora_animation_module::module_dir::write`). The header ships as JSON
// because that is the form the browser loaders take (`arora-web`'s
// `loadModule`, `@vizij/runtime`'s `modules` option). The records ship as YAML
// files, the form a module directory and `arora-web`'s `withRecords` take them
// in.

import { execFileSync } from "node:child_process";
import { writeFileSync, readdirSync, readFileSync, rmSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const pkgDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = resolve(pkgDir, "../../..");
const artifactDir = resolve(pkgDir, "artifact");
// cargo builds under CARGO_TARGET_DIR when the environment sets it.
const targetDir = resolve(repoRoot, process.env.CARGO_TARGET_DIR ?? "target");

execFileSync(
  "cargo",
  ["build", "-p", "arora-animation-module", "--target", "wasm32-wasip1", "--release"],
  { cwd: repoRoot, stdio: "inherit" },
);

// Written afresh, so a file the module directory no longer holds does not
// linger.
rmSync(artifactDir, { recursive: true, force: true });
execFileSync(
  "cargo",
  [
    "run",
    "-q",
    "-p",
    "vizij-animation-artifact",
    "--",
    artifactDir,
    resolve(targetDir, "wasm32-wasip1/release/arora_animation_module.wasm"),
  ],
  { cwd: repoRoot, stdio: ["ignore", "inherit", "inherit"] },
);

// The guest's URL, as a literal a bundler rewrites: the file name is the
// crate's, so the package names whatever the module directory holds.
const guests = readdirSync(artifactDir).filter((file) => file.endsWith(".wasm"));
if (guests.length !== 1) {
  throw new Error(`artifact/ holds ${guests.length} guests: ${guests.join(", ")}`);
}
writeFileSync(
  resolve(pkgDir, "src", "wasm-url.generated.ts"),
  "// @generated by scripts/build-artifact.mjs — do not edit.\n" +
    "/** URL of the packaged module executable (`wasm32-wasip1`). */\n" +
    `export const wasmUrl = new URL(${JSON.stringify(`../artifact/${guests[0]}`)}, import.meta.url);\n`,
);

// Inline the header into a generated source: loaders use this constant instead
// of fetching artifact/header.json, so no bundler asset plumbing is involved —
// a dev server that answers a missing asset with the SPA fallback (HTML) would
// break the module load with "headerJson is not a module header".
const header = JSON.parse(readFileSync(resolve(artifactDir, "header.json"), "utf8"));
writeFileSync(
  resolve(pkgDir, "src", "header-json.generated.ts"),
  "// @generated by scripts/build-artifact.mjs — do not edit.\n" +
    "/** The module's Arora header (JSON), inlined at artifact-build time. */\n" +
    `export const headerJson: string = ${JSON.stringify(JSON.stringify(header))};\n`,
);

// The records, inlined as each file's path under `records/` mapped to its
// YAML — the map `withRecords` takes — for the same reason as the header.
const recordsDir = resolve(artifactDir, "records");
const records = {};
for (const kind of readdirSync(recordsDir).sort()) {
  for (const file of readdirSync(resolve(recordsDir, kind)).sort()) {
    records[`${kind}/${file}`] = readFileSync(resolve(recordsDir, kind, file), "utf8");
  }
}
writeFileSync(
  resolve(pkgDir, "src", "records.generated.ts"),
  "// @generated by scripts/build-artifact.mjs — do not edit.\n" +
    "/** The module's Arora records, inlined at artifact-build time: each record\n" +
    " * file's path under `records/` mapped to its YAML. */\n" +
    `export const records: Record<string, string> = ${JSON.stringify(records, null, 2)};\n`,
);

console.log("[animation-module] artifact/ updated");
